#!/usr/bin/env python3 -I
"""Writes Localization/*.lproj from scripts/translations_tr.py and checks that
every localizable string in Sources/ has a Turkish translation."""
import json, os, re, subprocess, sys, glob
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
from translations_tr import TR, EN_PLURALS

def esc(s): return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")

tr_dir = os.path.join(ROOT, "Localization", "tr.lproj"); os.makedirs(tr_dir, exist_ok=True)
en_dir = os.path.join(ROOT, "Localization", "en.lproj"); os.makedirs(en_dir, exist_ok=True)
with open(os.path.join(tr_dir, "Localizable.strings"), "w") as f:
    f.write("/* Generated by scripts/generate-localizations.py — edit translations_tr.py */\n\n")
    for k in sorted(TR): f.write(f'"{esc(k)}" = "{esc(TR[k])}";\n')

def plist_str(s): return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
with open(os.path.join(en_dir, "Localizable.stringsdict"), "w") as f:
    f.write('<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n<plist version="1.0">\n<dict>\n')
    for k, (one, other) in sorted(EN_PLURALS.items()):
        f.write(f"  <key>{plist_str(k)}</key>\n  <dict>\n    <key>NSStringLocalizedFormatKey</key><string>%#@n@</string>\n")
        # The plural variable must use the integer; other args are positional in the forms.
        f.write("    <key>n</key>\n    <dict>\n      <key>NSStringFormatSpecTypeKey</key><string>NSStringPluralRuleType</string>\n"
                "      <key>NSStringFormatValueTypeKey</key><string>lld</string>\n"
                f"      <key>one</key><string>{plist_str(one)}</string>\n      <key>other</key><string>{plist_str(other)}</string>\n    </dict>\n  </dict>\n")
    f.write("</dict>\n</plist>\n")

# Coverage check
keys = json.loads(subprocess.check_output([sys.executable, os.path.join(ROOT, "scripts", "extract-strings.py"), "--json"], cwd=ROOT))
missing = [k for k in keys if k not in TR]
unused = [k for k in TR if k not in keys]
if unused: print("unused translations:", *unused, sep="\n  ")
if missing:
    print("MISSING translations:", *missing, sep="\n  "); sys.exit(1)
print(f"ok: {len(TR)} Turkish strings, {len(EN_PLURALS)} English plural rules")
